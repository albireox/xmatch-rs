#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct XMatchOptions {
    pub version: String,
    pub epoch: f32,
    pub pixelation_order: u8,
    pub n_workers: Option<usize>,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
#[serde(rename_all = "lowercase")]
pub enum CoordUnit {
    Degrees,
    Hours,
    Radians,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub enum EpochFormat {
    #[serde(rename = "jyear")]
    JulianYear,
    #[serde(rename = "jd")]
    Jd,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct XMatchModel {
    pub version: String,
    pub epoch: f32,
    pub pixelation_order: u8,
    #[serde(default)]
    pub catalogues: Vec<CatalogueModel>,
}

impl XMatchModel {
    pub fn read(path: impl AsRef<Path>) -> Result<Self> {
        let data = fs::read_to_string(path.as_ref())?;
        Ok(serde_yaml::from_str(&data)?)
    }

    pub fn write(&self, path: impl AsRef<Path>) -> Result<()> {
        let mut content =
            String::from("# This file was generated by xmatch_rs. Do not edit manually.\n\n");
        content.push_str(&serde_yaml::to_string(self)?);
        fs::write(path.as_ref(), content)?;
        Ok(())
    }
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct CatalogueModel {
    pub name: String,
    #[serde(default)]
    pub plan: Option<String>,
    pub run_id: i64,
    pub hats_path: PathBuf,
    #[serde(default = "default_xmatch_rs_version")]
    pub xmatch_rs_version: String,
    #[serde(default = "default_added_on")]
    pub added_on: String,
    pub primary_key: String,
    pub ra_column: String,
    #[serde(default = "default_coord_unit_degrees")]
    pub ra_column_unit: CoordUnit,
    pub dec_column: String,
    #[serde(default = "default_coord_unit_degrees")]
    pub dec_column_unit: CoordUnit,
    #[serde(default)]
    pub pmra_column: Option<String>,
    #[serde(default)]
    pub pmra_is_cosdec: Option<bool>,
    #[serde(default)]
    pub pmdec_column: Option<String>,
    #[serde(default)]
    pub epoch: Option<f64>,
    #[serde(default)]
    pub epoch_format: Option<EpochFormat>,
    #[serde(default)]
    pub epoch_column: Option<String>,
    #[serde(default)]
    pub phases: Vec<PhaseModel>,
}

impl CatalogueModel {
    pub fn get_phase(&self, phase_number: i64) -> Option<&PhaseModel> {
        self.phases.iter().find(|phase| phase.phase == phase_number)
    }

    pub fn get_phase_mut(&mut self, phase_number: i64) -> Option<&mut PhaseModel> {
        self.phases
            .iter_mut()
            .find(|phase| phase.phase == phase_number)
    }

    pub fn add_phase(&mut self, phase_model: PhaseModel) {
        self.delete_phase(phase_model.phase);
        self.phases.push(phase_model);
        self.phases.sort_by_key(|p| p.phase);
    }

    pub fn add_phases<I>(&mut self, phase_models: I)
    where
        I: IntoIterator<Item = PhaseModel>,
    {
        for phase in phase_models {
            self.add_phase(phase);
        }
    }

    pub fn delete_phase(&mut self, phase_number: i64) {
        self.phases.retain(|phase| phase.phase != phase_number);
        self.phases.sort_by_key(|p| p.phase);
    }

    pub fn delete_phases<I>(&mut self, phase_numbers: I)
    where
        I: IntoIterator<Item = i64>,
    {
        for phase_number in phase_numbers {
            self.delete_phase(phase_number);
        }
    }
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct PhaseModel {
    pub phase: i64,
    pub skipped: bool,
    pub n_matched: Option<i64>,
    #[serde(default)]
    pub join_paths: Vec<(String, String)>,
    pub query_radius: Option<f64>,
}

impl PhaseModel {
    pub fn validate(&self) -> Result<()> {
        if !self.join_paths.is_empty() && self.phase != 1 {
            bail!("join_paths should only be provided for phase 1.");
        }

        let source_col_re = Regex::new(r"^[a-zA-Z_][a-zA-Z0-9_]*$")?;
        let destination_col_re = Regex::new(r"^[a-zA-Z_][a-zA-Z0-9_]*\.[a-zA-Z_][a-zA-Z0-9_]*$")?;

        for (source, destination) in &self.join_paths {
            if !source_col_re.is_match(source) {
                bail!("Invalid column: {source}");
            }
            if !destination_col_re.is_match(destination) {
                bail!("Invalid destination column: {destination}");
            }
        }

        if self.query_radius.is_some() && self.phase != 2 {
            bail!("query_radius should only be provided for phase 2.");
        }

        if self.phase == 2 && self.query_radius.is_none() {
            bail!("query_radius is required for phase 2.");
        }

        Ok(())
    }
}

fn default_added_on() -> String {
    Utc::now().format("%Y-%m-%d %H:%M:%S").to_string()
}

fn default_coord_unit_degrees() -> CoordUnit {
    CoordUnit::Degrees
}

fn default_xmatch_rs_version() -> String {
    env!("CARGO_PKG_VERSION").to_string()
}

pub static CATALOG_SCHEMA: LazyLock<Schema> = LazyLock::new(|| {
    Schema::from_iter(vec![
        Field::new("catalogid".into(), DataType::UInt64),
        Field::new("healpix_29".into(), DataType::UInt64),
        Field::new("ra".into(), DataType::Float64),
        Field::new("dec".into(), DataType::Float64),
        Field::new("pmra".into(), DataType::Float64),
        Field::new("pmdec".into(), DataType::Float64),
        Field::new("epoch".into(), DataType::Float32),
        Field::new("added_by".into(), DataType::String),
        Field::new(
            "added_on".into(),
            DataType::Datetime(TimeUnit::Milliseconds, Some(TimeZone::UTC)),
        ),
        Field::new("version".into(), DataType::String),
    ])
});

pub fn cast_and_reorder(lf: LazyFrame, target_schema: &Schema) -> Result<LazyFrame> {
    // Create a hashmap with the target schema fields and datatypes.
    let cast_from_schema = PlHashMap::from_iter(
        CATALOG_SCHEMA
            .iter()
            .map(|field| (field.0.as_str(), field.1.clone())),
    );

    // List of columns in the target schema order.
    let target_columns: Vec<String> = target_schema
        .iter()
        .map(|field| field.0.to_string())
        .collect();

    // Cast the LazyFrame.
    let lf = lf.clone().cast(cast_from_schema, true);

    // Reorder the columns to match the target schema.
    let lf = lf.select(
        target_columns
            .iter()
            .map(|col_name| col(col_name.as_str()))
            .collect::<Vec<_>>(),
    );

    Ok(lf)
}
