from __future__ import annotations

import datetime
import pathlib
import re

from typing import Annotated

import yaml
from pydantic import (
    BaseModel,
    Field,
    PlainSerializer,
    SerializerFunctionWrapHandler,
    field_validator,
    model_serializer,
)

from xmatch_rs import __version__
from xmatch_rs.schema.schema import CoordUnit, EpochFormat


__all__ = ["XMatchModel", "CatalogueModel", "PhaseModel"]


class XMatchModel(BaseModel):
    """Pydantic model for the XMatch product."""

    version: Annotated[
        str,
        Field(description="Version of the XMatch product."),
    ]

    epoch: Annotated[
        float,
        Field(description="The epoch of the coordinates as Julian year."),
    ]

    pixelation_order: Annotated[
        int,
        Field(description="HEALPix order use to pixelate the unit sphere."),
    ]

    catalogues: Annotated[
        list[CatalogueModel],
        Field(
            description="List of catalogues included in the XMatch product.",
            default_factory=list,
        ),
    ]

    # Cache the file path.
    _file_path: pathlib.Path | None = None

    @classmethod
    def read(cls, path: str | pathlib.Path) -> XMatchModel:
        """Reads the XMatch model from a YAML file.

        Parameters
        ----------
        path
            The path to the input YAML file.

        Returns
        -------
        XMatchModel
            The XMatch model read from the file.

        """

        path = pathlib.Path(path)

        with open(path, "r") as f:
            data = yaml.safe_load(f)

        obj = cls.model_validate(data)
        obj._file_path = path

        return obj

    def write(self, path: str | pathlib.Path | None = None):
        """Writes the XMatch model to a YAML file.

        Parameters
        ----------
        path
            The path to the output YAML file.

        """

        if path is None:
            if self._file_path is None:
                raise ValueError("No file path specified for writing the model.")
            path = self._file_path

        path = pathlib.Path(path)

        with open(path, "w") as f:
            f.write("# This file was generated by xmatch_rs. Do not edit manually.\n\n")
            yaml.dump(self.model_dump(mode="json"), stream=f, sort_keys=False, indent=2)

        self._file_path = path

    def list_catalogue_names(self) -> list[str]:
        """Returns a list of the names of the catalogues included in the model."""

        return [catalogue.name for catalogue in self.catalogues]


class CatalogueModel(BaseModel):
    """Pydantic model for a catalogue included in the XMatch product."""

    name: Annotated[
        str,
        Field(description="Name of the catalogue."),
    ]

    plan: Annotated[
        str | None,
        Field(description="The plan used to cross-match this catalogue.", default=None),
    ]

    run_id: Annotated[
        int,
        Field(description="The run ID of the cross-match for this catalogue."),
    ]

    hats_path: Annotated[
        pathlib.Path,
        Field(description="Path to the HATS collection for this catalogue."),
    ]

    xmatch_rs_version: Annotated[
        str,
        Field(description="Version of xmatch_rs used to cross-match this catalogue."),
    ] = __version__ if __version__ is not None else "unknown"

    added_on: Annotated[
        datetime.datetime,
        Field(description="The date and time when this catalogue was added."),
        PlainSerializer(lambda dt: dt.strftime("%Y-%m-%d %H:%M:%S"), return_type=str),
    ] = datetime.datetime.now(tz=datetime.timezone.utc)

    primary_key: Annotated[
        str,
        Field(description="The primary key column for the catalogue."),
    ]

    ra_column: Annotated[
        str,
        Field(description="The RA column in the catalogue (in degrees)."),
    ]

    ra_column_unit: Annotated[
        CoordUnit,
        Field(description="The unit of the RA column."),
    ] = CoordUnit.DEGREES

    dec_column: Annotated[
        str,
        Field(description="The Dec column in the catalogue."),
    ]

    dec_column_unit: Annotated[
        CoordUnit,
        Field(description="The unit of the Dec column."),
    ] = CoordUnit.DEGREES

    pmra_column: Annotated[
        str | None,
        Field(description="The proper motion in RA column."),
    ] = None

    pmra_is_cosdec: Annotated[
        bool | None,
        Field(
            description="Whether the proper motion in RA column has already been "
            "deprojected by multiplying by cos(dec)."
        ),
    ] = None

    pmdec_column: Annotated[
        str | None,
        Field(description="The proper motion in Dec column."),
    ] = None

    epoch: Annotated[
        float | None,
        Field(description="The epoch of the coordinates as Julian year."),
    ] = None

    epoch_format: Annotated[
        EpochFormat | None,
        Field(description="The format of the epoch."),
    ] = None

    epoch_column: Annotated[
        str | None,
        Field(description="The column containing the epoch of the coordinates."),
    ] = None

    phases: Annotated[
        list[PhaseModel],
        Field(
            description="List of cross-match phases run for this cataloge.",
            default_factory=list,
        ),
    ]

    def get_phase(self, phase_number: int) -> PhaseModel | None:
        """Returns the phase model for a given phase number."""

        for phase in self.phases:
            if phase.phase == phase_number:
                return phase

        return None

    def add_phase(self, phase_model: PhaseModel | list[PhaseModel]):
        """Adds or updates a phase model to the catalogue model."""

        if isinstance(phase_model, (list, tuple)):
            for model in phase_model:
                self.add_phase(model)
            return

        if self.get_phase(phase_model.phase) is not None:
            self.delete_phase(phase_model.phase)

        self.phases.append(phase_model)

        # Reorder phases by phase number
        self.phases.sort(key=lambda p: p.phase)

    def delete_phase(self, phase_number: int | list[int]):
        """Deletes the phase model for a given phase number."""

        if isinstance(phase_number, (list, tuple)):
            for num in phase_number:
                self.delete_phase(num)
            return

        self.phases = [phase for phase in self.phases if phase.phase != phase_number]

        # Reorder phases by phase number
        self.phases.sort(key=lambda p: p.phase)


class PhaseModel(BaseModel):
    """Pydantic model for a cross-match phase run for a catalogue."""

    phase: Annotated[
        int,
        Field(description="The phase number."),
    ]

    skipped: Annotated[
        bool,
        Field(description="Whether this phase was skipped."),
    ] = False

    n_workers: Annotated[
        int | None,
        Field(description="The number of workers used for this phase."),
    ] = None

    n_matched: Annotated[
        int | None,
        Field(description="The number of sources matched in this phase."),
    ] = None

    join_paths: Annotated[
        list[tuple[str, str]],
        Field(
            description="List of join paths used in phase 1. Each join path is a "
            "tuple of (this_catalogue_column, other_catalogue.other_column).",
            default_factory=list,
        ),
    ]

    query_radius: Annotated[
        float | None,
        Field(
            description="The query radius used in phase 2, in arcseconds.",
            validate_default=True,
        ),
    ] = None

    @field_validator("join_paths", mode="before")
    @classmethod
    def validate_join_paths(cls, v, info):
        """Validator for the ``join_paths`` field."""

        if v != [] and info.data.get("phase") != 1:
            raise ValueError("join_paths should only be provided for phase 1.")

        for join_path in v:
            if not isinstance(join_path, (list, tuple)) or len(join_path) != 2:
                raise ValueError("Each join path should be a tuple.")

            if not re.match(r"^[a-zA-Z_][a-zA-Z0-9_]*$", join_path[0]):
                raise ValueError(f"Invalid column: {join_path[0]}")

            if not re.match(
                r"^[a-zA-Z_][a-zA-Z0-9_]*\.[a-zA-Z_][a-zA-Z0-9_]*$",
                join_path[1],
            ):
                raise ValueError(f"Invalid destination column: {join_path[1]}")

        return v

    @field_validator("query_radius", mode="before")
    @classmethod
    def validate_query_radius(cls, v, info):
        """Validator for the ``query_radius`` field."""

        phase = info.data.get("phase")

        if v is not None and phase != 2:
            raise ValueError("query_radius should only be provided for phase 2.")

        if phase == 2 and v is None:
            raise ValueError("query_radius is required for phase 2.")

        return v

    @model_serializer(mode="wrap")
    def serialize_model(
        self,
        handler: SerializerFunctionWrapHandler,
    ) -> dict[str, object]:
        """Custom serializer for the phase model.

        Skips null fields.

        """

        data = handler(self)
        phase = data.get("phase")

        if data["n_matched"] is None:
            del data["n_matched"]

        if phase != 1 and data["join_paths"] == []:
            del data["join_paths"]

        if phase != 2 and data["query_radius"] is None:
            del data["query_radius"]

        return data
