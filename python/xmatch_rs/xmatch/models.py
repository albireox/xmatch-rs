from __future__ import annotations

import datetime
import pathlib
import re
import warnings

from typing import Annotated, Literal

import yaml
from pydantic import (
    BaseModel,
    Field,
    PlainSerializer,
    SerializerFunctionWrapHandler,
    ValidationInfo,
    field_validator,
    model_serializer,
    model_validator,
)

from xmatch_rs import __version__
from xmatch_rs.schema.schema import CoordUnit, EpochFormat


__all__ = ["XMatchModel", "CatalogueModel", "PhaseModel"]


class XMatchModel(BaseModel):
    """Pydantic model for the XMatch product."""

    version: Annotated[
        str,
        Field(description="Version of the XMatch product."),
    ]

    epoch: Annotated[
        float,
        Field(description="The epoch of the coordinates as Julian year."),
    ]

    pixelation_order: Annotated[
        int,
        Field(description="HEALPix order use to pixelate the unit sphere."),
    ]

    catalogues: Annotated[
        list[CatalogueModel],
        Field(
            description="List of catalogues included in the XMatch product.",
            default_factory=list,
        ),
    ]

    # Cache the file path.
    _file_path: pathlib.Path | None = None

    @classmethod
    def read(cls, path: str | pathlib.Path) -> XMatchModel:
        """Reads the XMatch model from a YAML file.

        Parameters
        ----------
        path
            The path to the input YAML file.

        Returns
        -------
        XMatchModel
            The XMatch model read from the file.

        """

        path = pathlib.Path(path)

        with open(path, "r") as f:
            data = yaml.safe_load(f)

        obj = cls.model_validate(data)
        obj._file_path = path

        return obj

    def write(self, path: str | pathlib.Path | None = None):
        """Writes the XMatch model to a YAML file.

        Parameters
        ----------
        path
            The path to the output YAML file.

        """

        if path is None:
            if self._file_path is None:
                raise ValueError("No file path specified for writing the model.")
            path = self._file_path

        path = pathlib.Path(path)

        with open(path, "w") as f:
            f.write("# This file was generated by xmatch_rs. Do not edit manually.\n\n")
            yaml.dump(self.model_dump(mode="json"), stream=f, sort_keys=False, indent=2)

        self._file_path = path

    def list_catalogue_names(self) -> list[str]:
        """Returns a list of the names of the catalogues included in the model."""

        return [catalogue.name for catalogue in self.catalogues]


class CatalogueModel(BaseModel):
    """Pydantic model for a catalogue included in the XMatch product."""

    name: Annotated[
        str,
        Field(description="Name of the catalogue."),
    ]

    plan: Annotated[
        str | None,
        Field(description="The plan used to cross-match this catalogue.", default=None),
    ]

    run_id: Annotated[
        int,
        Field(description="The run ID of the cross-match for this catalogue."),
    ]

    hats_path: Annotated[
        pathlib.Path,
        Field(description="Path to the HATS collection for this catalogue."),
    ]

    xmatch_rs_version: Annotated[
        str,
        Field(description="Version of xmatch_rs used to cross-match this catalogue."),
    ] = __version__ if __version__ is not None else "unknown"

    added_on: Annotated[
        datetime.datetime,
        Field(description="The date and time when this catalogue was added."),
        PlainSerializer(lambda dt: dt.strftime("%Y-%m-%d %H:%M:%S"), return_type=str),
    ] = datetime.datetime.now(tz=datetime.timezone.utc)

    complete: Annotated[
        bool,
        Field(description="Whether the cross-match for this catalogue is complete."),
    ] = False

    primary_key: Annotated[
        str,
        Field(description="The primary key column for the catalogue."),
    ]

    ra_column: Annotated[
        str,
        Field(description="The RA column in the catalogue (in degrees)."),
    ]

    ra_column_unit: Annotated[
        CoordUnit,
        Field(description="The unit of the RA column."),
    ] = CoordUnit.DEGREES

    dec_column: Annotated[
        str,
        Field(description="The Dec column in the catalogue."),
    ]

    dec_column_unit: Annotated[
        CoordUnit,
        Field(description="The unit of the Dec column."),
    ] = CoordUnit.DEGREES

    pmra_column: Annotated[
        str | None,
        Field(description="The proper motion in RA column."),
    ] = None

    pmra_is_cosdec: Annotated[
        bool | None,
        Field(
            description="Whether the proper motion in RA column has already been "
            "deprojected by multiplying by cos(dec)."
        ),
    ] = None

    pmdec_column: Annotated[
        str | None,
        Field(description="The proper motion in Dec column."),
    ] = None

    epoch: Annotated[
        float | None,
        Field(description="The epoch of the coordinates as Julian year."),
    ] = None

    epoch_format: Annotated[
        EpochFormat | None,
        Field(description="The format of the epoch."),
    ] = None

    epoch_column: Annotated[
        str | None,
        Field(description="The column containing the epoch of the coordinates."),
    ] = None

    phases: Annotated[
        list[PhaseModel],
        Field(
            description="List of cross-match phases run for this cataloge.",
            default_factory=list,
        ),
    ]

    def get_phase(self, phase_number: int) -> PhaseModel | None:
        """Returns the phase model for a given phase number."""

        for phase in self.phases:
            if phase.phase == phase_number:
                return phase

        return None

    def add_phase(self, phase_model: PhaseModel | list[PhaseModel]):
        """Adds or updates a phase model to the catalogue model."""

        if isinstance(phase_model, (list, tuple)):
            for model in phase_model:
                self.add_phase(model)
            return

        if self.get_phase(phase_model.phase) is not None:
            self.delete_phase(phase_model.phase)

        self.phases.append(phase_model)

        # Reorder phases by phase number
        self.phases.sort(key=lambda p: p.phase)

    def delete_phase(self, phase_number: int | list[int]):
        """Deletes the phase model for a given phase number."""

        if isinstance(phase_number, (list, tuple)):
            for num in phase_number:
                self.delete_phase(num)
            return

        self.phases = [phase for phase in self.phases if phase.phase != phase_number]

        # Reorder phases by phase number
        self.phases.sort(key=lambda p: p.phase)


class PhaseModel(BaseModel):
    """Pydantic model for a cross-match phase run for a catalogue."""

    phase: Annotated[
        int,
        Field(description="The phase number."),
    ]

    complete: Annotated[
        bool,
        Field(description="Whether this phase is complete."),
    ] = False

    n_workers: Annotated[
        int | None,
        Field(description="The number of workers used for this phase."),
    ] = None

    n_matched: Annotated[
        int | None,
        Field(description="The number of sources matched in this phase."),
    ] = None

    join_paths: Annotated[
        list[JoinPathModel],
        Field(
            description="List of join paths used in phase 1.",
            default_factory=list,
        ),
    ]

    query_radius: Annotated[
        float | None,
        Field(
            description="The query radius used in phase 2, in arcseconds.",
            validate_default=True,
        ),
    ] = None

    @field_validator("join_paths", mode="before")
    @classmethod
    def validate_join_paths(cls, v, info: ValidationInfo):
        """Validator for the ``join_paths`` field."""

        phase = info.data.get("phase")

        if not isinstance(v, list):
            raise ValueError("join_paths must be a list.")

        if phase != 1 and len(v) > 0:
            raise ValueError("join_paths is only allowed for phase 1.")

        return v

    @field_validator("query_radius", mode="before")
    @classmethod
    def validate_query_radius(cls, v, info: ValidationInfo):
        """Validator for the ``query_radius`` field."""

        phase = info.data.get("phase")

        if v is not None and phase != 2:
            raise ValueError("query_radius is only allowed for phase 2.")

        if phase == 2 and v is None:
            raise ValueError("query_radius is required for phase 2.")

        return v

    @model_serializer(mode="wrap")
    def serialize_model(
        self,
        handler: SerializerFunctionWrapHandler,
    ) -> dict[str, object]:
        """Custom serializer for the phase model.

        Skips null fields.

        """

        data = handler(self)
        phase = data.get("phase")

        if data["n_matched"] is None:
            del data["n_matched"]

        if phase != 1 and data["join_paths"] == []:
            del data["join_paths"]

        if phase != 2 and data["query_radius"] is None:
            del data["query_radius"]

        return data


class JoinPathModel(BaseModel):
    """Pydantic model for a join path used in phase 1."""

    join_type: Annotated[
        Literal["column", "join_table"],
        Field(
            description="The type of join used. Can be 'column' to use an existing "
            "column in the catalogue being cross-matched, or 'join_table' to use an "
            "external relational table."
        ),
    ] = "column"

    left_on: Annotated[
        str,
        Field(
            description="The name of the column in the catalogue being "
            "cross-matched to use for the join."
        ),
    ]

    right_catalogue: Annotated[
        str,
        Field(
            description="The name of the catalogue to join with. Must be a "
            "catalogue that has already been cross-matched."
        ),
    ]

    right_on: Annotated[
        str,
        Field(description="The name of the column in the catalogue to join with."),
    ]

    join_table_path: Annotated[
        str | pathlib.Path | None,
        Field(
            description="The path on disk to the join table to use for the join. "
            "Must be readable using polars.scan_parquet. Only required if "
            "join_type is 'join_table'."
        ),
    ] = None

    join_table_left_on: Annotated[
        str | None,
        Field(
            description="The name of the column in the join table to join "
            "with the 'left_on' column. Only required if join_type is 'join_table'."
        ),
    ] = None

    join_table_right_on: Annotated[
        str | None,
        Field(
            description="The name of the column in the join table to join "
            "with the 'right_on' column. Only required if join_type is 'join_table'."
        ),
    ] = None

    join_table_type: Annotated[
        Literal["gaia_neighbourhood", "gaia_best_neighbour"] | None,
        Field(
            description="The type of join table. Only required if join_type is "
            "'join_table'. Accepted values are null for a normal join table, "
            "'gaia_neighbourhood', or 'gaia_best_neighbour'. The details of the join "
            "may change depending on the type of join table used."
        ),
    ] = None

    @field_validator(
        "left_on",
        "right_on",
        "join_table_left_on",
        "join_table_right_on",
        mode="before",
    )
    @classmethod
    def validate_column(cls, v: str | None, info: ValidationInfo):
        """Validator for the ``join_paths`` field."""

        if v is None:
            if info.field_name in ["left_on", "right_on"]:
                raise ValueError(f"{info.field_name} is required.")
            else:
                return v

        if not re.match(r"^[a-zA-Z_][a-zA-Z0-9_]*$", v):
            raise ValueError(f"Invalid column: {v!r}.")

        return v

    @model_validator(mode="after")
    def validate_join_path_model(self):
        """Validator the join path model."""

        if self.join_type == "join_table":
            if not self.join_table_path:
                raise ValueError(
                    "join_table_path is required when join_type is 'join_table'."
                )

            if not self.join_table_left_on:
                raise ValueError(
                    "join_table_left_on is required when join_type is 'join_table'."
                )

            if not self.join_table_right_on:
                raise ValueError(
                    "join_table_right_on is required when join_type is 'join_table'."
                )

        else:
            if self.join_table_path:
                warnings.warn(
                    "join_table_path is ignored when join_type is 'column'.",
                    UserWarning,
                )

            if self.join_table_left_on:
                warnings.warn(
                    "join_table_left_on is ignored when join_type is 'column'.",
                    UserWarning,
                )

            if self.join_table_right_on:
                warnings.warn(
                    "join_table_right_on is ignored when join_type is 'column'.",
                    UserWarning,
                )

        return self

    @field_validator("join_table_path")
    @classmethod
    def validate_join_table_path(
        cls,
        v: str | pathlib.Path | None,
    ) -> pathlib.Path | None:
        """Validator for the ``join_table_path`` field."""

        if v is None:
            return v

        path = pathlib.Path(v)

        if not path.exists():
            raise ValueError(f"join_table_path does not exist: {path}")

        return path
